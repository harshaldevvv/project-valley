import { launch } from './browser.mjs';
const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; page.on('pageerror', e => errs.push((e.stack || String(e)).slice(0, 300))); page.on('console', m => m.type() === 'error' && errs.push(m.text().slice(0, 200)));
await page.goto('http://localhost:5188/?play');
await page.waitForFunction(() => window.__gp && window.__gp.ctx.game.tick > 30, null, { timeout: 120000 });
await page.waitForTimeout(2000); await page.mouse.click(640, 360);
await page.evaluate(() => { window.__gp.sandbox(); });
await page.keyboard.press('Digit1'); await page.waitForTimeout(1200);
await page.evaluate(() => { const w = window.__gp.ctx.weapons; if (w.item) w.item.rounds = 0; });
await page.mouse.down(); await page.waitForTimeout(150); await page.mouse.up(); await page.waitForTimeout(300);
await page.keyboard.press('KeyR'); await page.waitForTimeout(3200);
await page.keyboard.press('Digit3'); await page.waitForTimeout(900); await page.keyboard.press('Digit1'); await page.waitForTimeout(1500);
console.log('errors', errs); await browser.close();
